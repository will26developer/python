# Operadores aritmeticos

num1: int = 30
num2: int = 45

print(f"Suma: {num1} + {num2} = {num1 + num2}")
print(f"Resta: {num1} + {num2} = {num1 - num2}")
print(f"Multiplicacion: {num1} * {num2} = {num1 * num2}")
print(f"Division entera: {num2} // {num1} = {num2 // num1}")
print(f"Division flotante: {num2} / {num1} = {num2 / num1}")
print(f"Resto: {num2} % {num1} = {num2 % num1}")
print(f"Potencia: {num1}**2 = {num2**2}")
